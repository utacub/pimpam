# Gegants del blau (CE38, 0.36): gathers the GLSL sources of this folder into dist/gegants-shaders.js.
# Run after editing any .glsl file: python3 production/gegants/make_shaders.py
# scene_00 .. scene_19 are the twenty scenes (scene_NN is the scene NN+1); scene_20 is the surface at sunset (the climb after the
# twentieth, and the rest picture before the first press).
from pathlib import Path
import json,os
here=Path(__file__).resolve().parent
r=lambda n:(here/n).read_text()
EMPTY='// not written yet\nvoid scene(vec2 w,float T){BG=openWater(w,T,1.,1.);}\n'
scenes=[(here/f'scene_{i:02d}.glsl') for i in range(21)]
out=['// Generated by production/gegants/make_shaders.py from the .glsl files of that folder: do not edit here.',
 'export const GG_GLSL=Object.freeze({',
 ' common:'+json.dumps(r('common.glsl'))+',',
 ' head:'+json.dumps(r('scene_head.glsl'))+',',
 ' tail:'+json.dumps(r('scene_tail.glsl'))+',',
 ' scenes:Object.freeze(['+','.join(json.dumps(p.read_text() if p.exists() else EMPTY) for p in scenes)+'])',
 '});','']
dst=here.parent.parent/'dist'/'gegants-shaders.js';tmp=dst.with_name(f'gegants-shaders.{os.getpid()}.tmp')
tmp.write_text('\n'.join(out));os.replace(tmp,dst)
print('dist/gegants-shaders.js:',sum(p.exists() for p in scenes),'of 21 scenes written,',dst.stat().st_size,'bytes')
