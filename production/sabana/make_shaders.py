# Sabana de paper (CE36, 0.30): gathers the GLSL sources of this folder into dist/sabana-shaders.js.
# Run after editing any .glsl file: python3 production/sabana/make_shaders.py
from pathlib import Path
import json
here=Path(__file__).resolve().parent
r=lambda n:(here/n).read_text()
EMPTY='// not written yet\nvoid scene(vec2 q,float t){}\n'
scenes=[(here/f'scene_{i:02d}.glsl') for i in range(20)]
out=['// Generated by production/sabana/make_shaders.py from the .glsl files of that folder: do not edit here.',
 'export const SABANA_GLSL=Object.freeze({',
 ' common:'+json.dumps(r('common.glsl'))+',',
 ' bg:'+json.dumps(r('bg.glsl'))+',',
 ' near:'+json.dumps(r('near.glsl'))+',',
 ' head:'+json.dumps(r('scene_head.glsl'))+',',
 ' tail:'+json.dumps(r('scene_tail.glsl'))+',',
 ' scenes:Object.freeze(['+','.join(json.dumps(p.read_text() if p.exists() else EMPTY) for p in scenes)+'])',
 '});','']
(here.parent.parent/'dist'/'sabana-shaders.js').write_text('\n'.join(out))
print('dist/sabana-shaders.js:',sum(p.exists() for p in scenes),'scenes written')
