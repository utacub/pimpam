# Fons marí de vidre (0.28): gathers the GLSL sources of this folder into dist/fons-shaders.js (one string per shader), so that the
# app and the standalone HTML carry them. Run after editing any .glsl file: python3 production/fons_mari/make_shaders.py
from pathlib import Path
import json
here=Path(__file__).resolve().parent
dist=here.parent.parent/'dist'
r=lambda n:(here/n).read_text()
scenes=sorted(here.glob('scene_[0-9][0-9].glsl'))
out=['// Generated by production/fons_mari/make_shaders.py from the .glsl files of that folder: do not edit here.',
 'export const FONS_GLSL=Object.freeze({',
 ' common:'+json.dumps(r('common.glsl'))+',',
 ' bg:'+json.dumps(r('bg.glsl'))+',',
 ' head:'+json.dumps(r('scene_head.glsl'))+',',
 ' tail:'+json.dumps(r('scene_tail.glsl'))+',',
 ' scenes:Object.freeze(['+','.join(json.dumps(p.read_text()) for p in scenes)+'])',
 '});','']
(dist/'fons-shaders.js').write_text('\n'.join(out))
print(f'dist/fons-shaders.js: {len(scenes)} scenes')
