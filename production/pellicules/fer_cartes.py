# 0.50 · The card picture of each film of «Petites pel·lícules»: one frame of one of its sequences, 640×360 JPEG, written as data URIs
# into dist/pellicules-cartes.js (so that the menu never has to load a video). Run from the repository root:
#   python3 production/pellicules/fer_cartes.py
import base64,json,subprocess,tempfile,os
from pathlib import Path
root=Path(__file__).resolve().parents[2];vids=root/'dist'/'videos'
FRAMES={'mos':('mos/mos_03.mp4',1.0),'comunicar':('comunicar/comunicar_01.mp4',1.5)}
out={}
for id,(f,t) in FRAMES.items():
 src=vids/f
 if not src.exists():continue
 with tempfile.TemporaryDirectory() as d:
  jpg=os.path.join(d,'c.jpg');subprocess.run(['ffmpeg','-nostdin','-v','error','-y','-ss',str(t),'-i',str(src),'-frames:v','1','-vf','scale=640:360','-q:v','4',jpg],check=True)
  out[id]='data:image/jpeg;base64,'+base64.b64encode(Path(jpg).read_bytes()).decode()
(root/'dist'/'pellicules-cartes.js').write_text('// Generated by production/pellicules/fer_cartes.py: the card picture of each film (a frame of one of its sequences, JPEG).\nexport const PL_CARD=Object.freeze('+json.dumps(out,separators=(',',':'))+');\n')
print({k:len(v) for k,v in out.items()})
