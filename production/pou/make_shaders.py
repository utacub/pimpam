# El pou del temps (CE37, 0.31): gathers the GLSL sources of this folder into dist/pou-shaders.js.
# Run after editing any .glsl file: python3 production/pou/make_shaders.py
# scene_00 .. scene_19 are the twenty scenes (scene_NN is the scene NN+1); scene_20 is the garden of today at the top of the well.
from pathlib import Path
import json
here=Path(__file__).resolve().parent
r=lambda n:(here/n).read_text()
EMPTY='// not written yet\nconst vec2 WIN_C=vec2(0.);\nvoid fossil(vec2 q){}\nvoid life(vec2 q,float t){sky(q,vec3(.45,.55,.72),vec3(.86,.80,.70),-.1);}\n'
scenes=[(here/f'scene_{i:02d}.glsl') for i in range(21)]
out=['// Generated by production/pou/make_shaders.py from the .glsl files of that folder: do not edit here.',
 'export const POU_GLSL=Object.freeze({',
 ' common:'+json.dumps(r('common.glsl'))+',',
 ' rock:'+json.dumps(r('rock.glsl'))+',',
 ' head:'+json.dumps(r('scene_head.glsl'))+',',
 ' tail:'+json.dumps(r('scene_tail.glsl'))+',',
 ' scenes:Object.freeze(['+','.join(json.dumps(p.read_text() if p.exists() else EMPTY) for p in scenes)+'])',
 '});','']
import os
dst=here.parent.parent/'dist'/'pou-shaders.js';tmp=dst.with_name(f'pou-shaders.{os.getpid()}.tmp')
tmp.write_text('\n'.join(out));os.replace(tmp,dst)  # atomic: several painters run this at once
print('dist/pou-shaders.js:',sum(p.exists() for p in scenes),'of 21 scenes written')
